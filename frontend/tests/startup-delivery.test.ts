import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { createHash } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import { startupPreloadFiles } from '../build/publicStartupPreload'

describe('mandatory startup-only discovery', () => {
  const chunk = (name: string, facade: string | null, imports: string[] = [], dynamicImports: string[] = [], isEntry = false) => ({
    type: 'chunk' as const, fileName: name, facadeModuleId: facade, imports, dynamicImports, isEntry,
  })
  const bundle = () => ({
    'assets/entry-A.js': chunk('assets/entry-A.js', 'C:/frontend/src/public-main.tsx', [], ['assets/app-B.js'], true),
    'assets/app-B.js': chunk('assets/app-B.js', 'C:/frontend/src/PublicBetaApp.tsx', ['assets/shared-C.js'], ['assets/route-D.js']),
    'assets/shared-C.js': chunk('assets/shared-C.js', null, ['assets/entry-A.js']),
    'assets/route-D.js': chunk('assets/route-D.js', 'C:/frontend/src/pages/PublicMarketPage.tsx'),
  })
  it('walks only shell static imports, handles cycles and ignores all optional routes', () => {
    expect(startupPreloadFiles(bundle())).toEqual(['assets/app-B.js', 'assets/shared-C.js'])
  })
  it('fails closed if shell identity or dependency is missing or unsafe', () => {
    const missing = bundle(); missing['assets/app-B.js'].facadeModuleId = '/src/wrong.tsx'
    expect(() => startupPreloadFiles(missing)).toThrow('mandatory shell missing')
    const unsafe = bundle(); unsafe['assets/app-B.js'].imports = ['https://example.test/a.js']
    expect(() => startupPreloadFiles(unsafe)).toThrow('unsafe static dependency')
  })
  it('recognizes Vite HTML entry proxies by their rendered public-main module', () => {
    const proxy = { ...bundle()['assets/entry-A.js'], facadeModuleId: '/frontend/index.html', modules: { '/frontend/src/public-main.tsx': {} } }
    expect(startupPreloadFiles({ ...bundle(), 'assets/entry-A.js': proxy })).toEqual(['assets/app-B.js', 'assets/shared-C.js'])
  })
})

const codePoints = (ranges: string[]) => {
  const points = new Set<number>()
  for (const range of ranges.flatMap((value) => value.split(','))) {
    const [a, b] = range.trim().replace(/^U\+/iu, '').split('-').map((value) => parseInt(value, 16))
    for (let point = a; point <= (b ?? a); point++) points.add(point)
  }
  return points
}
describe('English five-glyph UI subsets', () => {
  const root = resolve(import.meta.dirname, '../src/assets/fonts/ui-symbols')
  const manifest = JSON.parse(readFileSync(resolve(root, 'manifest.json'), 'utf8')) as { source_version: string; records: { file: string; source: string; sha256: string; source_sha256: string; bytes: number; codepoints: number[] }[] }
  const css = readFileSync(resolve(root, 'ui-symbols.css'), 'utf8')
  const digest = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex')
  it('pins original source and generated bytes without replacing the Chinese font', () => {
    expect(manifest.source_version).toBe('5.3.0')
    expect(manifest.records).toHaveLength(4)
    for (const record of manifest.records) {
      const bytes = readFileSync(resolve(root, record.file))
      expect(digest(bytes)).toBe(record.sha256)
      expect(bytes.length).toBe(record.bytes)
      expect(digest(readFileSync(resolve(import.meta.dirname, '../node_modules/@fontsource-variable/noto-sans-sc/files', record.source)))).toBe(record.source_sha256)
      expect(css).toContain("url('./" + record.file + "')")
    }
    expect(manifest.records.reduce((sum, record) => sum + record.bytes, 0)).toBeLessThan(24000)
  })
  it('covers only the five audited UI symbols and keeps variable weights and swap', () => {
    const expected = new Set([0x2190, 0x2192, 0x2605, 0x2606, 0xff1a])
    expect(new Set(manifest.records.flatMap((record) => record.codepoints))).toEqual(expected)
    expect(codePoints([...css.matchAll(/unicode-range:\s*([^;]+);/gu)].map((match) => match[1]))).toEqual(expected)
    expect(css.match(/font-weight: 100 900;/gu)).toHaveLength(4)
    expect(css.match(/font-display: swap;/gu)).toHaveLength(4)
    expect(readFileSync(resolve(root, 'LICENSE'), 'utf8')).toContain('SIL OPEN FONT LICENSE Version 1.1')
  })
})
