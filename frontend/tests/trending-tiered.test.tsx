import { fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import fixture from '../../schemas/examples/single-item-trending-tiered-list.valid.json'
import { LangProvider } from '../src/i18n'
import { PublicTrendingPage } from '../src/pages/PublicTrendingPage'
import { decodeTrendingPublicDocument } from '../src/wire/singleItemTrendingPublicApiDecode'
import type { TrendingListQuery } from '../src/wire/singleItemTrendingPublicApiTypes'

const query = { as_of: null, publication_id: null, direction: 'GAINERS', page_size: 50,
  cursor: null, filters: { item_kind: null, base_item_code: null, edition_kind: null, wear_tier: null },
} satisfies TrendingListQuery

afterEach(() => { vi.restoreAllMocks(); vi.useRealTimers() })

describe('additive source-tiered V3 contract', () => {
  it('decodes bytes generated by the real Python producer and API', () => {
    const result = decodeTrendingPublicDocument(fixture, query, 200)
    expect(result.api_version).toBe('v3')
    expect(Object.isFrozen(result)).toBe(true)
    expect(JSON.stringify(result)).not.toMatch(/source_asset_ref|identity_binding|start_cny_minor/u)
  })

  it.each(['grade', 'pair', 'coverage', 'reason', 'private', 'downgrade', 'gradeTotals'])('rejects %s drift', (change) => {
    const payload: any = structuredClone(fixture)
    const row = payload.members.find((r: any) => r.evidence_grade === 'TWO_SOURCE_SUPPORTED')
    if (change === 'grade') row.evidence_grade = 'THREE_SOURCE_CONFIRMED'
    if (change === 'pair') row.supporting_sources = ['market_a', 'market_a']
    if (change === 'coverage') payload.publication.accounting.qualified_supported_endpoint_count--
    if (change === 'reason') row.unavailable_sources[0].end_reason = 'SOURCE_REFRESH_LAG'
    if (change === 'private') row.source_asset_ref = 'private'
    if (change === 'downgrade') payload.api_version = 'v2'
    if (change === 'gradeTotals') {
      payload.publication.accounting.three_source_confirmed_count = payload.publication.accounting.status_counts.ELIGIBLE_A3 = 2
      payload.publication.accounting.two_source_supported_count = payload.publication.accounting.status_counts.ELIGIBLE_A2 = 0
    }
    expect(() => decodeTrendingPublicDocument(payload, query, 200)).toThrow()
  })

  it.each(['zh', 'en'] as const)('renders source grades, absence and fixed denominator in %s', async (lang) => {
    render(<LangProvider lang={lang}><PublicTrendingPage
      gateway={{ kind: 'SYNTHETIC_TIERED_TEST', async read(request) {
        const payload = structuredClone(fixture)
        payload.query.page_size = request.page_size
        return { payload, httpStatus: 200 }
      } }}
      asOf={null} publicationId={null} direction="GAINERS" filters={query.filters}
      catalogHref="/catalog" onCatalogClick={() => {}} onQueryChange={() => {}}
    /></LangProvider>)
    const coverage = await screen.findByTestId('public-trending-coverage')
    fireEvent.click(coverage.querySelector('summary')!)
    expect(coverage).toHaveTextContent(lang === 'zh' ? '固定集合 2 项' : 'Fixed universe: 2')
    expect(await screen.findByText(lang === 'zh' ? '双源支持（第三源未确认）'
      : 'Two-source supported (third source unconfirmed)')).toBeInTheDocument()
    expect(screen.getByTestId('public-trending-page')).toHaveTextContent(lang === 'zh'
      ? '市场 B：起端 采样中无有效挂单；末端 采样中无有效挂单'
      : 'Market B: start No active ask in sampled slots; end No active ask in sampled slots')
  })
})
